import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const output = new URL('web/app.bundle.js', root);
const result = await build({
  absWorkingDir: fileURLToPath(root),
  entryPoints: [fileURLToPath(new URL('web/js/app.js', root))],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome61'],
  // Stay within the independently checked ES2017 grammar (Chrome 61 also
  // supports object spread, but lowering it gives the parser check one baseline).
  supported: { 'object-rest-spread': false },
  charset: 'utf8',
  legalComments: 'none',
  write: false,
  banner: { js: '// Generated by tests/build-web.mjs (esbuild 0.25.12, chrome61). Do not edit.' },
});
const generated = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  const current = await readFile(output, 'utf8');
  if (current !== generated) throw Error('Stale web/app.bundle.js; run npm --prefix tests run build and bump web/sw.js cache version.');
  console.log('web/app.bundle.js matches the Chrome 61 build.');
} else {
  await writeFile(output, generated);
  console.log('Built web/app.bundle.js for Chrome 61 (no runtime dependencies).');
}
