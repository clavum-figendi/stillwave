import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Two classic bundles: the page bootstrap and the AudioWorklet processor. Both target Chrome 61 syntax.
const root = new URL('../', import.meta.url);
const bundles = [['web/js/app.js', 'web/app.bundle.js'], ['web/js/worklet.js', 'web/worklet.bundle.js']];
const check = process.argv.includes('--check');
for (const [entry, out] of bundles) {
  const result = await build({
    absWorkingDir: fileURLToPath(root),
    entryPoints: [fileURLToPath(new URL(entry, root))],
    bundle: true, format: 'iife', platform: 'browser', target: ['chrome61'],
    // Stay within the independently checked ES2017 grammar.
    supported: { 'object-rest-spread': false },
    charset: 'utf8', legalComments: 'none', write: false,
    banner: { js: '// Generated by tests/build-web.mjs (esbuild 0.25.12, chrome61). Do not edit.' },
  });
  const generated = result.outputFiles[0].text, output = new URL(out, root);
  if (check) {
    if (await readFile(output, 'utf8') !== generated) throw Error(`Stale ${out}; run npm --prefix tests run build and bump web/sw.js cache version.`);
    console.log(`${out} matches the Chrome 61 build.`);
  } else { await writeFile(output, generated); console.log(`Built ${out} for Chrome 61 (no runtime dependencies).`); }
}
